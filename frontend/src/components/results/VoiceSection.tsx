import { usePlayback, usePlaybackState } from '../../hooks/usePlayback'
import { formatTimestamp } from '../../lib/highlight'
import { ModelNote, Limitations } from '../ModelNote'
import { VOICE_VIEW } from '../../lib/views'
import type { VoiceAssessment } from '../../lib/types'

export function VoiceSection({ voice }: { voice: VoiceAssessment }) {
  const controller = usePlayback()
  const playback = usePlaybackState()
  const view = VOICE_VIEW[voice.verdict]
  const scored = voice.windows.length > 0 && voice.fake_score_median !== null
  return (
    <section aria-labelledby="voice-heading">
      <p className="font-mono text-sm text-accent">02 · Voice authenticity</p>
      <h2 id="voice-heading" className="mt-2 flex items-center gap-3 font-display text-3xl font-medium sm:text-4xl">
        <span className={`size-3 shrink-0 rounded-full ${view.dot}`} aria-hidden />
        {view.label}
      </h2>
      <p className="mt-3 text-ink-2">{voice.summary}</p>
      {voice.error && <p className="mt-2 text-danger">{voice.error}</p>}
      {voice.verdict !== 'unavailable' && (
        <p className="mt-3 text-sm text-ink-3">
          Source: voice-authenticity analysis of the audio signal only. The classifier returns a score and does not say which sounds or features led to it, so this page cannot explain why. It detected a voice-related signal, nothing more specific.
        </p>
      )}

      {scored && voice.fake_score_median !== null && (
        <div className="mt-8">
          <div className="flex items-end gap-4">
            <p className="font-display text-5xl font-medium leading-none tabular-nums">{voice.fake_score_median.toFixed(2)}</p>
            <p className="pb-1 text-sm text-ink-2">
              median “fake” label score, not a probability
              <br />
              across {voice.windows_analyzed} window{voice.windows_analyzed === 1 ? '' : 's'}
            </p>
          </div>

          <div className="mt-8" role="img" aria-label={`Scale from 0 to 1. Median fake score ${voice.fake_score_median.toFixed(2)}. Window scores: ${voice.windows.map((w) => w.fake_score.toFixed(2)).join(', ')}.`}>
            <div className="relative h-8">
              <div className="absolute inset-x-0 top-1/2 h-1 -translate-y-1/2 rounded-full bg-gradient-to-r from-accent-tint via-paper-2 to-amber-tint" />
              <div className="absolute left-1/2 top-1/2 h-5 w-px -translate-y-1/2 bg-ink-3" />
              {voice.windows.map((window) => (
                <span
                  key={window.start_seconds}
                  className="absolute top-1/2 size-2.5 -translate-x-1/2 -translate-y-1/2 rounded-full border border-ink bg-card"
                  style={{ left: `${window.fake_score * 100}%` }}
                />
              ))}
              <span
                className="absolute top-1/2 size-5 -translate-x-1/2 -translate-y-1/2 rounded-full bg-ink ring-4 ring-paper"
                style={{ left: `${voice.fake_score_median * 100}%` }}
              />
            </div>
            <div className="mt-1 grid grid-cols-3 text-xs text-ink-3">
              <span>0 · “real” label</span>
              <span className="text-center">0.5</span>
              <span className="text-right">“fake” label · 1</span>
            </div>
          </div>
          <p className="mt-3 text-sm text-ink-3">
            The score is the model’s output for its “fake” label: 0 favors its “real” label, 1 favors “fake”. Small dots are individual windows and the large dot is their median. It is a normalized model score, not a calibrated probability, and a high score does not show the recording was generated by AI.
          </p>

          <ul aria-label="Scores by window" className="mt-5 space-y-1">
            {voice.windows.map((window) => {
              const label = `${formatTimestamp(window.start_seconds)} to ${formatTimestamp(window.end_seconds)}, score ${window.fake_score.toFixed(2)}`
              const row = (
                <>
                  <span className="w-24 shrink-0 font-mono text-xs tabular-nums text-ink-2">
                    {formatTimestamp(window.start_seconds)}–{formatTimestamp(window.end_seconds)}
                  </span>
                  <span className="h-1.5 flex-1 rounded-full bg-paper-2" aria-hidden>
                    <span className="block h-1.5 rounded-full bg-ink-3" style={{ width: `${window.fake_score * 100}%` }} />
                  </span>
                  <span className="w-10 text-right font-mono text-xs tabular-nums">{window.fake_score.toFixed(2)}</span>
                </>
              )
              return (
                <li key={window.start_seconds}>
                  {playback.status === 'ready' ? (
                    <button type="button" onClick={() => controller?.seek(window.start_seconds)} aria-label={`${label}. Jump to this window.`} className="flex w-full items-center gap-3 rounded-md px-1 py-1 hover:bg-paper-2 pointer-coarse:min-h-11">
                      {row}
                    </button>
                  ) : (
                    <p className="flex items-center gap-3 px-1 py-1" aria-label={label}>
                      {row}
                    </p>
                  )}
                </li>
              )
            })}
          </ul>

          <dl className="mt-6 grid grid-cols-2 gap-6 border-t border-line pt-5 text-sm">
            <div>
              <dt className="text-ink-3">Windows at or above 0.5</dt>
              <dd className="mt-0.5 font-display text-2xl tabular-nums">
                {voice.windows_favoring_fake} of {voice.windows_analyzed}
              </dd>
            </div>
            <div>
              <dt className="text-ink-3">Highest window score</dt>
              <dd className="mt-0.5 font-display text-2xl tabular-nums">{voice.fake_score_max?.toFixed(2) ?? '—'}</dd>
            </div>
          </dl>
        </div>
      )}

      {voice.verdict !== 'unavailable' && voice.reliability_caution && (
        <p className="mt-6 border-l-2 border-amber-light pl-4 text-sm text-ink-2">{voice.reliability_caution}</p>
      )}

      {voice.verdict !== 'unavailable' && (
        <details className="mt-4 text-sm">
          <summary className="flex cursor-pointer items-center text-accent underline-offset-4 hover:underline pointer-coarse:min-h-11">How this score is produced</summary>
          {voice.score_note && <p className="mt-2 text-ink-2">{voice.score_note}</p>}
          {voice.decision_rule && <p className="mt-2 text-ink-2">{voice.decision_rule}</p>}
          <ModelNote model={voice.model} />
          <Limitations items={voice.limitations} />
        </details>
      )}
    </section>
  )
}
